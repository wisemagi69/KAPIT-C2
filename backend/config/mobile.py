"""Inactive-by-default mobile auth policy; invalid config never disables M1.

Only the later mobile adapters may require this configuration. No route,
credential generation, database write or mobile application import happens here.
"""
import base64
from dataclasses import dataclass, field
from importlib import metadata
import re
import secrets

JWT_PACKAGE_VERSION = "2.15.1"
PROTOCOL = "kapit-mobile-v1"
JWT_ALGORITHM = "HS256"
JWT_ISSUER = "kapit-local-mobile"
JWT_AUDIENCE = "kapit-android"
ACCESS_LIFETIME_SECONDS = 600
FAMILY_LIFETIME_SECONDS = 604800
OFFLINE_LEASE_SECONDS = 86400
CHALLENGE_LIFETIME_SECONDS = 120
JWT_LEEWAY_SECONDS = 0


class MobileConfigurationUnavailable(RuntimeError):
    """Adapters map this fixed, non-secret failure to MOBILE_UNAVAILABLE/503."""

    def __init__(self):
        super().__init__("Mobile authentication configuration is unavailable.")


@dataclass(frozen=True, slots=True)
class MobileAuthConfig:
    enabled: bool
    unavailable_reason: str | None
    signing_key: bytes | None = field(default=None, repr=False)
    protocol: str = field(default=PROTOCOL, init=False)
    algorithm: str = field(default=JWT_ALGORITHM, init=False)
    issuer: str = field(default=JWT_ISSUER, init=False)
    audience: str = field(default=JWT_AUDIENCE, init=False)
    access_lifetime_seconds: int = field(default=ACCESS_LIFETIME_SECONDS, init=False)
    family_lifetime_seconds: int = field(default=FAMILY_LIFETIME_SECONDS, init=False)
    offline_lease_seconds: int = field(default=OFFLINE_LEASE_SECONDS, init=False)
    challenge_lifetime_seconds: int = field(default=CHALLENGE_LIFETIME_SECONDS, init=False)
    leeway_seconds: int = field(default=JWT_LEEWAY_SECONDS, init=False)

    @property
    def available(self):
        return self.enabled and self.unavailable_reason is None and self.signing_key is not None

    def require_available(self):
        if not self.available:
            raise MobileConfigurationUnavailable()
        return self


def _decoded_key(value):
    # Use a bounded canonical representation, not a user-selected passphrase.
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z0-9_-]{43,86}", value):
        return None
    try:
        decoded = base64.b64decode(value + "=" * (-len(value) % 4), altchars=b"-_", validate=True)
    except ValueError:
        return None
    if not 32 <= len(decoded) <= 64 or base64.urlsafe_b64encode(decoded).rstrip(b"=").decode("ascii") != value:
        return None
    return decoded


def _other_key_forms(value):
    if not isinstance(value, str) or not value:
        return ()
    forms = [value.encode("utf8")]
    # Compare bytes too: stripping Fernet padding must not disguise key reuse.
    if re.fullmatch(r"[A-Za-z0-9_-]+={0,2}", value):
        unpadded = value.rstrip("=")
        try:
            forms.append(base64.b64decode(unpadded + "=" * (-len(unpadded) % 4), altchars=b"-_", validate=True))
        except ValueError:
            pass
    return forms


def load_mobile_config(environment, *, django_secret, source_key, database_password):
    """Return unavailable metadata, never an import failure or generated key.

    Key material must be generated by the future owned harness using a CSPRNG.
    Encoding/length, obvious repetition and known reuse checks cannot prove its
    randomness; that remains an explicit custody/provisioning requirement.
    """
    flag = environment.get("KAPIT_MOBILE_ENABLED", "0")
    if flag not in {"0", "1"}:
        return MobileAuthConfig(False, "MOBILE_FLAG_INVALID")
    if flag == "0":
        return MobileAuthConfig(False, "MOBILE_DISABLED")
    encoded = environment.get("KAPIT_MOBILE_SIGNING_KEY")
    if encoded is None or encoded == "":
        return MobileAuthConfig(True, "MOBILE_KEY_MISSING")
    key = _decoded_key(encoded)
    if key is None or len(set(key)) < 16:
        return MobileAuthConfig(True, "MOBILE_KEY_INVALID")
    for existing in (django_secret, source_key, database_password):
        if any(secrets.compare_digest(key, form) for form in _other_key_forms(existing)):
            return MobileAuthConfig(True, "MOBILE_KEY_REUSED")
    try:
        if metadata.version("PyJWT") != JWT_PACKAGE_VERSION:
            return MobileAuthConfig(True, "MOBILE_DEPENDENCY_UNAVAILABLE")
    except metadata.PackageNotFoundError:
        return MobileAuthConfig(True, "MOBILE_DEPENDENCY_UNAVAILABLE")
    return MobileAuthConfig(True, None, key)
